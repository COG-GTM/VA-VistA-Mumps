"""Render MAPPING.md and mapping.csv from data/dd_file2.json + field_map."""

from __future__ import annotations

import csv
from collections import Counter
from pathlib import Path

from .citations import permalink
from .field_map import DERIVED, NONE, OTHER, PARTIAL, PATIENT, STATUSES, classify

SECTIONS = (
    (PATIENT, "Mapped to FHIR R4 Patient"),
    (PARTIAL, "Mapped to Patient with loss or caveat"),
    (NONE, "Flagged: no FHIR R4 equivalent"),
    (OTHER, "Belongs on another FHIR resource (not Patient)"),
    (DERIVED, "Derived in VistA (not exchanged)"),
)


def rows(dd_json: dict) -> list[dict]:
    out = []
    for fileno, fields in dd_json["files"].items():
        for num, fd in fields.items():
            m = classify(fd)
            out.append({
                "file": fileno, "field": num, "name": fd["name"], "type": fd["type_spec"],
                "storage": fd["storage"].strip(), "status": m.status, "fhir": m.fhir, "note": m.note,
                "no_fhir_equivalent": "YES" if m.status == NONE else "",
                "dd_path": dd_json["source"], "dd_line": fd["dd_line"], "dd_raw": fd["dd_raw"],
                "routine_citations": fd["routine_citations"],
            })
    return sorted(out, key=lambda r: (float(r["file"]), float(r["field"])))


def _md(text: str) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def _code(text: str, limit: int = 110) -> str:
    text = text if len(text) <= limit else text[: limit - 1] + "…"
    return "`" + text.replace("`", "'").replace("|", "\\|") + "`"


def _ref_cell(r: dict) -> str:
    cites = [f"[{c['ref']}]({permalink(c['path'], c['line'])}) {_code(c['text'], 60)}"
             for c in r["routine_citations"]]
    return "<br>".join(cites)


def write_reports(out_dir: Path, dd_json: dict) -> None:
    data = rows(dd_json)
    counts = Counter(r["status"] for r in data)
    top = [r for r in data if r["file"] == "2"]
    lines = [
        "# VistA FileMan file #2 (PATIENT) → FHIR R4 Patient: field-by-field mapping",
        "",
        "Generated by `build_data.py` from "
        f"[`{dd_json['source']}`]({permalink(dd_json['source'], 1).rsplit('#', 1)[0]}) "
        f"at commit `{dd_json['source_sha'][:10]}`. Do not edit by hand.",
        "",
        f"{len(top)} top-level fields in file #2, plus {len(data) - len(top)} fields in the "
        "ALIAS, RACE, ETHNICITY, LANGUAGE and ICN-history subfiles that feed Patient elements.",
        "",
        "| Status | Fields |",
        "|---|---|",
        *[f"| {s} | {counts.get(s, 0)} |" for s in STATUSES],
        "",
        "**Columns.** *DD line* is the line in `DD.zwr` holding the field's FileMan 0-node "
        "(`^DD(file,field,0)` = name^type^set/pointer^node;piece^input transform M code); "
        "the text shown is that line verbatim (truncated). *Logic* links each `TAG^ROUTINE` "
        "called by the field's input transform to the line defining that tag. "
        "`DD.zwr` is too large for GitHub to render, so its line numbers are given as text; "
        "check one with `sed -n '<line>p' \"Packages/VA FileMan/Globals/DD.zwr\"`. "
        "Full, untruncated rows are in [`mapping.csv`](mapping.csv).",
        "",
        "Patient.id and the MR identifier come from the record IEN (DFN), which is not a field.",
        "",
    ]
    for status, title in SECTIONS:
        section = [r for r in data if r["status"] == status]
        lines += [f"## {title} ({len(section)})", ""]
        if status in (PATIENT, PARTIAL, OTHER):
            lines += ["| File | Field # | VistA field | Type | Node;piece | FHIR R4 | Notes | DD line (M) | Logic |",
                      "|---|---|---|---|---|---|---|---|---|"]
            for r in section:
                lines.append(
                    f"| {r['file']} | {r['field']} | {_md(r['name'])} | `{_md(r['type'])}` | `{_md(r['storage'])}` "
                    f"| {_md(r['fhir'])} | {_md(r['note'])} | L{r['dd_line']} {_code(r['dd_raw'])} | {_ref_cell(r)} |")
        else:
            lines += ["| File | Field # | VistA field | Type | Node;piece | Why | DD line (M) | Logic |",
                      "|---|---|---|---|---|---|---|---|"]
            for r in section:
                lines.append(
                    f"| {r['file']} | {r['field']} | {_md(r['name'])} | `{_md(r['type'])}` | `{_md(r['storage'])}` "
                    f"| {_md(r['note'])} | L{r['dd_line']} {_code(r['dd_raw'])} | {_ref_cell(r)} |")
        lines.append("")
    (out_dir / "MAPPING.md").write_text("\n".join(lines), encoding="utf-8")

    with open(out_dir / "mapping.csv", "w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh, lineterminator="\n")
        w.writerow(["file", "field", "name", "type", "storage", "status", "no_fhir_equivalent",
                    "fhir_element", "note", "dd_path", "dd_line", "dd_zero_node", "logic_citations"])
        for r in data:
            cites = "; ".join(f"{c['ref']} {c['path']}:{c['line']}" for c in r["routine_citations"])
            w.writerow([r["file"], r["field"], r["name"], r["type"], r["storage"], r["status"],
                        r["no_fhir_equivalent"], r["fhir"], r["note"], r["dd_path"], r["dd_line"],
                        r["dd_raw"], cites])
